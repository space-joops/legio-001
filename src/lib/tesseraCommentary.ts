/**
 * 뗏세라 기도문 **구절별 뜻풀이와 관련 성경**.
 *
 * `/tessera` 화면에서 구절을 누르면 뜨는 팝업의 내용이 여기서 나온다.
 * 타입과 묶는 함수는 `tesseraVerses.ts` 에 있고 여기는 **데이터만** 둔다 —
 * `rosaryMysteries.ts`(로직) ↔ `rosaryMeditations.ts`(데이터) 와 같은 구조다.
 *
 * ## 주소 체계
 *
 * 구절은 `(장, section, from..to)` 로 가리킨다. `section` 과 `from`/`to` 는
 * `tesseraTexts.ts` 의 `TESSERA_CHAPTERS[].entry.sections[].lines[]` 인덱스이며
 * `to` 는 **그 줄을 포함**한다. 줄 텍스트를 키로 쓰지 않는 이유는
 * `tesseraVerses.ts` 의 주석에 적어 두었다(같은 문장이 여러 곳에 나온다).
 *
 * ⚠️ `tesseraTexts.ts` 에서 줄을 넣거나 빼면 여기 번호가 **조용히** 밀린다.
 *    `src/__tests__/tesseraCommentary.test.ts` 가 176줄 전부가 빠짐없이 한 번씩만
 *    덮이는지 전수 검사하므로, 기도문을 고쳤다면 그 테스트를 먼저 돌릴 것.
 *
 * ## 성경 인용
 *
 * 본문은 한국 천주교 주교회의 「성경」(새번역)에서 옮겼고, 팝업 하단에 출처를
 * 표기한다. 약칭·장절 표기도 「성경」을 따른다(예: `루카 1,28` — 장과 절 사이는
 * 쉼표, 절 범위는 붙임표).
 *
 * ## 풀이를 쓸 때
 *
 * 읽는 분이 50대 이상인 것을 전제로 한다. 한자어를 쓰면 곧바로 풀어 주고,
 * 한 문단은 두세 문장을 넘기지 않는다. 교리를 새로 주장하지 말고 공인된 해설
 * 범위 안에서만 쓴다.
 *
 * [TS] `Record<TesseraChapterId, VerseCommentary[]>` 는 파이썬으로 치면
 *      `dict[TesseraChapterId, list[VerseCommentary]]` 다. 바깥 키는 장 4개로
 *      고정이라 하나라도 빠지면 컴파일 에러가 난다.
 *      → docs/typescript-for-python.md#6-타입
 */

